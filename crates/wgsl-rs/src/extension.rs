// Compile-time macro-claim verification helpers
// ---------------------------------------------------------------------------

/// Check if a `&str` slice contains a given needle, byte-by-byte.
///
/// This is a `const fn` because `str::PartialEq` is not yet stable in
/// `const` context. The `#[wgsl]` macro emits `const _: () = { ... }`
/// blocks that call this to verify every `Stmt::Macro` name is claimed by
/// at least one listed extension's `MACROS` const.
pub const fn contains_str(haystack: &[&str], needle: &str) -> bool {
    let nb = needle.as_bytes();
    let mut i = 0;
    while i < haystack.len() {
        let hb = haystack[i].as_bytes();
        if hb.len() == nb.len() {
            let mut j = 0;
            let mut eq = true;
            while j < nb.len() {
                if hb[j] != nb[j] {
                    eq = false;
                }
                j += 1;
            }
            if eq {
                return true;
            }
        }
        i += 1;
    }
    false
}

/// Check if any extension's `MACROS` list contains the given macro name.
///
/// `exts` is a slice of `MACROS` slices — one per extension listed in
/// `extensions = [...]`. Returns `true` if at least one extension claims
/// the macro.
pub const fn any_ext_claims(exts: &[&[&str]], name: &str) -> bool {
    let mut i = 0;
    while i < exts.len() {
        if contains_str(exts[i], name) {
            return true;
        }
        i += 1;
    }
    false
}
